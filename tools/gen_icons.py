#!/usr/bin/env python3
"""Turn the ASCII art icons below into keyboards/klaw/oled_icons.h.

Each icon is 16 x 16 pixels, '#' is lit. The header stores them as the OLED
frame buffer expects: 16 bytes for the upper 8 pixel rows, one byte per
column with bit 0 at the top, then 16 bytes for the lower rows.
"""
import pathlib

ICONS = {
    "caps": """
.......##.......
......####......
.....######.....
....########....
...##########...
..############..
.##############.
.....######.....
.....######.....
.....######.....
.....######.....
................
.##############.
.##############.
................
................
""",
    "audio": """
................
.........#......
....##....#.....
...###.#...#....
..####..#..#....
.#####..#.#.#...
######...#..#...
######...#..#...
######...#..#...
.#####..#.#.#...
..####..#..#....
...###.#...#....
....##....#.....
.........#......
................
................
""",
    "rgb": """
.....######.....
....#......#....
...#........#...
...#........#...
...#........#...
...#........#...
....#......#....
....#......#....
.....#....#.....
.....#....#.....
.....######.....
.....######.....
......####......
......####......
.......##.......
................
""",
}

out = ["// Generated by tools/gen_icons.py, edit the ASCII art there.", "#pragma once", "#include <stdint.h>", "#include \"progmem.h\"", "",
       "#define ICON_WIDTH 16", ""]
for name, art in ICONS.items():
    rows = [r for r in art.strip("\n").splitlines()]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), name
    data = []
    for page in range(2):
        for x in range(16):
            data.append(sum(1 << bit for bit in range(8) if rows[page * 8 + bit][x] == "#"))
    out.append(f"static const uint8_t PROGMEM icon_{name}[32] = {{")
    out.append("    " + ", ".join(f"0x{b:02X}" for b in data[:16]) + ",")
    out.append("    " + ", ".join(f"0x{b:02X}" for b in data[16:]) + ",")
    out.append("};")
    # round trip check
    back = ["".join("#" if data[(y // 8) * 16 + x] & (1 << (y % 8)) else "." for x in range(16)) for y in range(16)]
    assert back == rows, name
root = pathlib.Path(__file__).resolve().parent.parent
(root / "keyboards/klaw/oled_icons.h").write_text("\n".join(out) + "\n")
print(f"{len(ICONS)} icons written to keyboards/klaw/oled_icons.h")
